"""Turn the Excalidraw libraries in props-src/excalidraw/ into one prop file the board can draw:
templates/video/assets/props-ex.js  ->  SK.ex(key, tl, svg, x, y, at, {w | s, dur, color})

Every element becomes a rough.js stroke in the board's own ink (black strokes -> C.ink, coloured ones
-> C.pink, fills dropped), so the borrowed drawings look like ours and follow the board's colours.
Text inside library items is dropped (write labels as .lb HTML like everywhere else).
Also writes props-src/excalidraw/sheet.html, a contact sheet with every key, for picking.

usage: python3 -I scripts/excalidraw_props.py          (re-run after adding a library)
Sources and licence (MIT): props-src/excalidraw/LICENSE, https://github.com/excalidraw/excalidraw-libraries"""
import glob, json, math, os, re
from pathlib import Path

SK_DIR = Path(__file__).resolve().parent.parent
SRC = SK_DIR / "props-src/excalidraw"
OUT = SK_DIR / "templates/video/assets/props-ex.js"
INK = {"#000000", "#1e1e1e", "#000", "#343a40", "#495057", "transparent"}


def slug(s):
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")


def rot(px, py, cx, cy, a):
    if not a:
        return px, py
    c, s = math.cos(a), math.sin(a)
    return cx + (px - cx) * c - (py - cy) * s, cy + (px - cx) * s + (py - cy) * c


def convert(els):
    out = []
    for e in els:
        if e.get("isDeleted") or e["type"] in ("text", "image", "frame"):
            continue
        x, y, w, h, a = e["x"], e["y"], e.get("width", 0), e.get("height", 0), e.get("angle", 0) or 0
        cx, cy = x + w / 2, y + h / 2
        col = "pink" if (e.get("strokeColor", "#000").lower() not in INK) else "ink"
        sw = max(2.5, min(5, (e.get("strokeWidth", 1) or 1) * 2.5))
        if e["type"] == "ellipse" and not a:
            out.append({"t": "e", "cx": cx, "cy": cy, "w": w, "h": h, "c": col, "sw": sw})
        elif e["type"] in ("rectangle", "diamond", "ellipse"):
            if e["type"] == "rectangle":
                pts = [(x, y), (x + w, y), (x + w, y + h), (x, y + h), (x, y)]
            elif e["type"] == "diamond":
                pts = [(cx, y), (x + w, cy), (cx, y + h), (x, cy), (cx, y)]
            else:
                pts = [(cx + w / 2 * math.cos(t * math.pi / 12), cy + h / 2 * math.sin(t * math.pi / 12)) for t in range(25)]
            out.append({"t": "p", "pts": [rot(px, py, cx, cy, a) for px, py in pts], "c": col, "sw": sw})
        elif e["type"] in ("line", "arrow", "freedraw"):
            pts = [rot(x + px, y + py, cx, cy, a) for px, py in e.get("points", [])]
            if e["type"] == "freedraw" and len(pts) > 40:   # thin out hand strokes
                k = len(pts) // 40 + 1
                pts = pts[::k] + [pts[-1]]
            if len(pts) >= 2:
                out.append({"t": "p", "pts": pts, "c": col, "sw": sw, "smooth": e["type"] == "freedraw"})
    if not out:
        return None
    xs, ys = [], []
    for o in out:
        if o["t"] == "e":
            xs += [o["cx"] - o["w"] / 2, o["cx"] + o["w"] / 2]; ys += [o["cy"] - o["h"] / 2, o["cy"] + o["h"] / 2]
        else:
            xs += [p[0] for p in o["pts"]]; ys += [p[1] for p in o["pts"]]
    x0, y0 = min(xs), min(ys)
    r = lambda v: round(v, 1)
    for o in out:
        if o["t"] == "e":
            o["cx"], o["cy"], o["w"], o["h"] = r(o["cx"] - x0), r(o["cy"] - y0), r(o["w"]), r(o["h"])
        else:
            o["pts"] = [[r(px - x0), r(py - y0)] for px, py in o["pts"]]
    return {"w": r(max(xs) - x0), "h": r(max(ys) - y0), "els": out}


# readable names for libraries whose items have none (checked on the contact sheet)
NAMES = {"awesome-icons": {1: "list", 2: "cancel", 3: "search", 4: "trash", 5: "house", 6: "lock", 7: "clock",
                           8: "bookmark", 9: "bar-chart", 10: "briefcase", 11: "calendar", 12: "card", 13: "person",
                           14: "person-b", 15: "team", 16: "alarm", 17: "basket", 18: "pin", 19: "cursor", 20: "info",
                           21: "add", 22: "bell", 23: "mail", 24: "tag"},
         "computers": {1: "server-rack", 2: "desktop", 3: "laptop", 4: "tower"}}

lib = {}
for f in sorted(glob.glob(str(SRC / "*.excalidrawlib"))):
    d = json.load(open(f))
    items = d.get("libraryItems") or [{"elements": x} for x in d.get("library", [])]
    base = Path(f).stem
    for i, it in enumerate(items):
        p = convert(it["elements"])
        if p:
            key = base + "/" + (slug(it.get("name") or "") or NAMES.get(base, {}).get(i + 1) or "%02d" % (i + 1))
            while key in lib:
                key += "-b"
            lib[key] = p

JS = """/* Props borrowed from the Excalidraw libraries (MIT, see props-src/excalidraw/LICENSE),
   redrawn stroke by stroke in the board's ink. Generated by scripts/excalidraw_props.py — don't edit.
   SK.ex(key, tl, svg, x, y, at, o): x,y = top-left; o.w = width in px (or o.s = scale); o.dur = draw time.
   Returns the time the drawing ends. SK.exSize(key) -> {w, h}. Keys: props-src/excalidraw/sheet.html */
(function () {
  var SK = window.SK, C = SK.C, LIB = %s;
  SK.exSize = function (k) { return { w: LIB[k].w, h: LIB[k].h }; };
  SK.ex = function (k, tl, svg, x, y, at, o) {
    o = o || {};
    var it = LIB[k]; if (!it) throw new Error("no prop " + k);
    var s = o.s || (o.w ? o.w / it.w : 1), dur = o.dur || Math.min(1.6, 0.4 + 0.05 * it.els.length);
    var n = it.els.length, step = dur / n;
    it.els.forEach(function (e, i) {
      var col = o.color || (e.c === "pink" ? C.pink : C.ink), sw = e.sw * Math.max(0.6, Math.min(1.2, s));
      var g;
      if (e.t === "e") g = SK.ellipse(svg, x + e.cx * s, y + e.cy * s, e.w * s, e.h * s, { stroke: col, strokeWidth: sw });
      else {
        var d = e.pts.map(function (p, j) { return (j ? "L " : "M ") + (x + p[0] * s).toFixed(1) + " " + (y + p[1] * s).toFixed(1); }).join(" ");
        g = SK.path(svg, d, { stroke: col, strokeWidth: sw, roughness: e.smooth ? 0.4 : 0.9 });
      }
      SK.draw(tl, g, at + i * step, Math.max(0.12, step * 1.4));
    });
    return at + dur;
  };
})();
""" % json.dumps(lib, separators=(",", ":"))
OUT.write_text(JS)

cards = "".join('<div class="c"><svg viewBox="-6 -6 %s %s">%s</svg><b>%s</b></div>' % (
    p["w"] + 12, p["h"] + 12,
    "".join('<ellipse cx="%s" cy="%s" rx="%s" ry="%s"/>' % (e["cx"], e["cy"], e["w"] / 2, e["h"] / 2) if e["t"] == "e"
            else '<polyline points="%s"/>' % " ".join("%s,%s" % tuple(q) for q in e["pts"]) for e in p["els"]), k)
    for k, p in lib.items())
(SRC / "sheet.html").write_text("""<!doctype html><meta charset="utf-8"><title>Excalidraw props</title>
<style>body{background:#FAF4E8;font:13px system-ui;margin:16px;display:flex;flex-wrap:wrap;gap:10px}
.c{width:150px;height:150px;background:#fff;border:1px solid #ddd;display:flex;flex-direction:column;align-items:center;padding:6px}
svg{flex:1;width:130px;height:110px;fill:none;stroke:#2E2E33;stroke-width:2}b{font-weight:500;font-size:11px;text-align:center}</style>
""" + cards)
print(len(lib), "props ->", OUT, "| sheet:", SRC / "sheet.html")
