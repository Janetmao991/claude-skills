"""Turn a real-demo run into assets/real-data.js (window.REAL) for the video's paper screens.

Run after build_data.py and answer.py:
  python3 export_real_data.py <real-demo dir> <video project dir>
"""
import json, sys
from pathlib import Path

demo, proj = Path(sys.argv[1]), Path(sys.argv[2])
R = json.loads((demo / "data/results.json").read_text())
A = json.loads((demo / "data/answer.js").read_text().removeprefix("window.ANSWER=").rstrip().rstrip(";"))
out = {
    "model": R["model"], "endpoint": R["endpoint"], "query": R["query"],
    "vec": [round(x, 4) for x in R["query_response"]["data"][0]["embedding"]],
    "tokens": R["query_response"]["usage"]["total_tokens"],
    "docs": [{"id": d["id"], "title": d["title"], "vec3": [round(x, 3) for x in d["embedding"][:3]]} for d in R["docs"]],
    "ranked": [{"title": d["title"], "score": d["score"]} for d in R["ranked"]],
    "map": [{"text": p["text"], "group": p["group"], "xy": p["xy"]} for p in R["map"]],
    "pair": R["pair"],
    "answer": A,
}
p = proj / "assets/real-data.js"
p.write_text("// Real API output from real-demo/. Generated by export_real_data.py; do not edit by hand.\n"
             "window.REAL = " + json.dumps(out, ensure_ascii=False) + ";\n")
print("wrote", p, "·", len(out["vec"]), "dims")
