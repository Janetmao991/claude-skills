"""Camera keys from the pen strokes: during each voice line, push gently toward where the pen is drawing;
turn to the right column while a paper screen is up; back to full view at each new section.
Reads tools/strokes.json (tools/dump_strokes.sh) + assets/vo/timeline.js, writes assets/camera-keys.js.
Run: python3 tools/build_camera.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
S_PUSH, S_SCREEN, MOVE, MIN_SHIFT = 1.1, 1.08, 0.8, 120
SCREEN = (1400, 620)
SCENES = ["scene", "problem", "map", "steps", "api", "goal"]  # hook stays full frame
BLOCK_LINES = {"p3": "p3", "n1": "n1", "m5": "m6", "k4": "k4", "a3": "a4", "g2": "g3"}  # block in-line → last line


def main():
    s = (ROOT / "assets/vo/timeline.js").read_text()
    V = json.loads(s[s.index("{"): s.rindex("}") + 1])
    L, H = V["lines"], V.get("holds", {})
    end = lambda i: L[i]["end"] + H.get(i, 0)
    strokes = json.loads((ROOT / "tools/strokes.json").read_text())
    blocks = [(L[a]["start"] - 0.3, end(b) + 0.1) for a, b in BLOCK_LINES.items()]
    in_block = lambda t: any(a <= t <= b for a, b in blocks)
    keys, focus = [], (960, 540, 1.0)

    def key(t, cx, cy, sc, d=MOVE):
        nonlocal focus
        keys.append({"t": round(t, 3), "d": d, "cx": round(cx), "cy": round(cy), "s": sc})
        focus = (cx, cy, sc)

    for name in SCENES:
        sc = V["scenes"][name]
        key(sc["start"] - 0.6, 960, 540, 1.0, 0.7)
        for lid in sc["lines"]:
            t0, t1 = L[lid]["start"], end(lid)
            if lid in BLOCK_LINES:  # a paper screen comes up: look right, then come back
                key(t0 - 0.35, *SCREEN, S_SCREEN, 0.9)
                continue
            if in_block(t0):
                continue
            pts = [(x, y) for t, d, k, x, y in strokes if t0 - 0.2 <= t <= t1 and not in_block(t)]
            if not pts:
                continue
            cx = min(1440, max(480, sum(p[0] for p in pts) / len(pts)))
            cy = min(800, max(300, sum(p[1] for p in pts) / len(pts)))
            if focus[2] == 1.0 or abs(cx - focus[0]) + abs(cy - focus[1]) > MIN_SHIFT or focus[:2] == SCREEN:
                key(t0 + 0.05, cx, cy, S_PUSH)
        key(sc["end"] - 0.7, 960, 540, 1.0, 0.7)
    (ROOT / "assets/camera-keys.js").write_text(
        "// Generated by tools/build_camera.py from the pen strokes; do not edit by hand.\nwindow.CAMERA_KEYS = "
        + json.dumps(keys) + ";\n")
    print(len(keys), "camera keys → assets/camera-keys.js")


main()
